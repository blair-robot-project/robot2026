package frc.team449.subsystems.shooter

import edu.wpi.first.math.filter.Debouncer
import edu.wpi.first.units.Units.*
import edu.wpi.first.units.measure.Angle
import edu.wpi.first.units.measure.AngularVelocity
import edu.wpi.first.wpilibj2.command.Command
import edu.wpi.first.wpilibj2.command.Commands
import edu.wpi.first.wpilibj2.command.SubsystemBase
import frc.team449.Constants.ShooterConstants
import frc.team449.RobotContainer.fuelSim
import org.littletonrobotics.junction.Logger
import kotlin.math.abs

class ShooterSubsystem(
    private val io: ShooterIO
) : SubsystemBase() {
    var ballCount = 0

    // ignore the error in the ide, it's autogenerated
    private val inputs: ShooterIOInputsAutoLogged = ShooterIOInputsAutoLogged()

    private var flywheelTargetVelocityRadPerSec: Double = 0.0
    private var hoodTargetPositionRad: Double = 0.2591940418

    val hoodSimAngle: Double
        get() = inputs.hoodPositionRad

    var shootCooldown = 0

    private val flywheelDebouncer: Debouncer = Debouncer(ShooterConstants.TOLERANCE_DEBOUNCE_TIME, Debouncer.DebounceType.kRising)
    private val hoodDebouncer: Debouncer = Debouncer(ShooterConstants.TOLERANCE_DEBOUNCE_TIME, Debouncer.DebounceType.kRising)

    override fun periodic() {
        io.updateInputs(inputs)
        Logger.processInputs("Shooter", inputs)

        Logger.recordOutput("Shooter/FlywheelTargetRadPerSec", flywheelTargetVelocityRadPerSec)
        Logger.recordOutput("Shooter/HoodTargetRads", hoodTargetPositionRad)

        Logger.recordOutput("Shooter/FlywheelAtTolerance", isFlywheelAtTolerance())
        Logger.recordOutput("Shooter/HoodAtTolerance", isHoodAtTolerance())

        Logger.recordOutput("Shooter/Balls", ballCount)
    }

    override fun simulationPeriodic() {
        if (io is ShooterIOSim) {

            if (isFlywheelAtTolerance() && flywheelTargetVelocityRadPerSec >= 10 && shootCooldown <= 0 && ballCount > 0) {
                shootCooldown = 30

                val flywheelSurfaceSpeed = inputs.rightLeaderVelocityRadPerSec * ShooterConstants.FLYWHEEL_RADIUS
                val hoodRollerSurfaceSpeed = inputs.rightLeaderVelocityRadPerSec * 1 / ShooterConstants.HOOD_ROLLER_GEARING * ShooterConstants.HOOD_ROLLER_RADIUS.`in`(Meters)
                val effectiveShootSpeed = (flywheelSurfaceSpeed + hoodRollerSurfaceSpeed) / 2 * ShooterConstants.EFFICIENCY

                println("Shooting a ball at $effectiveShootSpeed m/s")

                fuelSim.launchFuel(
                    MetersPerSecond.of(effectiveShootSpeed),
                    Radians.of(inputs.hoodPositionRad),
                    Radians.of(0.0),
                    ShooterConstants.SHOOTER_HEIGHT,
                )
                ballCount -= 1
            }
            if (shootCooldown > 0) {
                shootCooldown -= 1
            }
        }
    }

    fun setFlywheelVelocity(velocity: AngularVelocity): Command =
        runOnce {
            flywheelTargetVelocityRadPerSec = velocity.`in`(RadiansPerSecond)
            io.setFlywheelVelocity(velocity)
        }

    fun stopFlywheel(): Command =
        runOnce {
            flywheelTargetVelocityRadPerSec = 0.0
            io.setFlywheelVoltage(0.0)
        }

    fun setHoodAngle(angle: Angle): Command =
        runOnce {
            hoodTargetPositionRad = angle.`in`(Radians)
            io.setHoodAngle(angle)
        }

    fun setHoodVoltage(volts: Double): Command =
        runOnce {
            io.setHoodVoltage(volts)
        }

    fun resetHoodPosition(angle: Angle): Command =
        runOnce {
            io.resetHoodPosition(angle)
        }

    fun isFlywheelAtTolerance(): Boolean {
        // if (target == 0.0) return false
        val leftError = abs(inputs.leftLeaderVelocityRadPerSec - flywheelTargetVelocityRadPerSec)
        val rightError = abs(inputs.rightLeaderVelocityRadPerSec - flywheelTargetVelocityRadPerSec)

        val isAtSpeed = leftError < ShooterConstants.FLYWHEEL_VELOCITY_TOLERANCE_RAD_PER_SEC &&
            rightError < ShooterConstants.FLYWHEEL_VELOCITY_TOLERANCE_RAD_PER_SEC

        return flywheelDebouncer.calculate(isAtSpeed)
    }

    fun isHoodAtTolerance(): Boolean {
        val error = abs(inputs.hoodPositionRad - hoodTargetPositionRad)

        val isAtPos = error < ShooterConstants.HOOD_TOLERANCE_RAD

        return hoodDebouncer.calculate(isAtPos)
    }

    fun homeHood(): Command {
        return this.defer {
            val homingDebouncer = Debouncer(ShooterConstants.HOMING_DEBOUNCE_TIME, Debouncer.DebounceType.kRising)

            Commands.sequence(
                this.runOnce { io.setHoodVoltage(ShooterConstants.HOMING_VOLTAGE) },
                Commands.waitUntil {
                    val highCurrent = abs(inputs.hoodStatorCurrentAmps) > ShooterConstants.HOMING_CURRENT_AMPS
                    val lowVelocity = abs(inputs.hoodVelocityRadPerSec) < ShooterConstants.HOMING_VELOCITY_RAD_PER_SEC
                    homingDebouncer.calculate(highCurrent && lowVelocity)
                },
                this.runOnce {
                    io.setHoodVoltage(0.0)
                    io.resetHoodPosition(ShooterConstants.MIN_HOOD_ANGLE)
                    io.setHoodAngle(ShooterConstants.MIN_HOOD_ANGLE)
                }
            )
        }.withName("Home Hood")
    }

    fun holdHood(): Command = setHoodAngle(Radians.of(inputs.hoodPositionRad))
}
